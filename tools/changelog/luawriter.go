package main

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"strings"
)

// luaHeader opens data/changelogdata.lua; the copy in the repository starts the same way.
const luaHeader = `-- Generated by tools/changelog. CI writes this file before packaging a release, with the notes
-- Gemini wrote for it and the releases before it; the copy in the repository is what a source
-- checkout shows.
local addonName = ... ---@type string

---@class BetterBags: AceAddon
local addon = LibStub('AceAddon-3.0'):GetAddon(addonName)

---@class ChangelogData: AceModule
---@field releases ChangelogRelease[]
local changelogData = addon:NewModule('ChangelogData')

`

// luaString quotes s as a Lua 5.1 string literal. Control characters are written as
// three-digit decimal escapes, so a digit after one is never read as part of it; other bytes
// (UTF-8 included) are written as they are.
func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"':
			b.WriteString(`\"`)
		case c == '\\':
			b.WriteString(`\\`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\r':
			b.WriteString(`\r`)
		case c == '\t':
			b.WriteString(`\t`)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// WriteLua writes the ChangelogData module holding releases.
func WriteLua(w io.Writer, releases []Release) error {
	out := bufio.NewWriter(w)
	out.WriteString(luaHeader)
	if len(releases) == 0 {
		out.WriteString("changelogData.releases = {}\n")
		return out.Flush()
	}
	out.WriteString("changelogData.releases = {\n")
	for _, r := range releases {
		out.WriteString("  {\n")
		fmt.Fprintf(out, "    id = %d,\n", r.ID)
		fmt.Fprintf(out, "    version = %s,\n", luaString(r.Version))
		fmt.Fprintf(out, "    channel = %s,\n", luaString(r.Channel))
		fmt.Fprintf(out, "    date = %s,\n", luaString(r.Date))
		fmt.Fprintf(out, "    headline = %s,\n", luaString(r.Headline))
		out.WriteString("    entries = {\n")
		for _, e := range r.Entries {
			out.WriteString("      {\n")
			fmt.Fprintf(out, "        category = %s,\n", luaString(e.Category))
			fmt.Fprintf(out, "        title = %s,\n", luaString(e.Title))
			fmt.Fprintf(out, "        details = %s,\n", luaString(e.Details))
			if len(e.Clients) == 0 {
				out.WriteString("        clients = {},\n")
			} else {
				quoted := make([]string, len(e.Clients))
				for i, c := range e.Clients {
					quoted[i] = luaString(c)
				}
				fmt.Fprintf(out, "        clients = { %s },\n", strings.Join(quoted, ", "))
			}
			out.WriteString("      },\n")
		}
		out.WriteString("    },\n")
		out.WriteString("  },\n")
	}
	out.WriteString("}\n")
	return out.Flush()
}

// writeData writes the ChangelogData module to path.
func writeData(path string, releases []Release) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	if err := WriteLua(f, releases); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}
