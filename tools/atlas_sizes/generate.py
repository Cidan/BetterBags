#!/usr/bin/env python3
"""Write spec/fixtures/atlas_sizes.lua: the size and tiling of every atlas BetterBags' themes name, as each client
reports them (C_Texture.GetAtlasInfo), read from the client's own tables (UiTextureAtlasElement, UiTextureAtlasMember)
through wago.tools. Atlas data is the game's, not the UI source's, so the specs cannot read it from
.libraries/wow-ui-source.

Usage: tools/atlas_sizes/generate.py <cache dir>   (run from the repository root; downloads into the cache dir)

The names: every quoted string in the themes, the names a theme builds in code (BUILT), and every atlas of the
nine-slice layout fixture, that is an atlas on the client. An element's size is its member's at 1x; an element whose only member is its -2x one (Blizzard's high-res
frame art) is half that, as the client reports it. CommittedFlags 4 tiles across, 2 tiles down (the "_" and "!" atlases).
"""
import csv
import glob
import json
import os
import re
import sys
import urllib.request

# The build of each client family BetterBags ships for (wago.tools /api/builds), newest at the time of writing.
BUILDS = {
    "Retail": ("wow", "12.1.5.70575"),
    "Forever": ("wowf", "1.60.1.70532"),
    "Era": ("wow_classic_era", "1.15.9.70003"),
    "Anniversary": ("wow_anniversary", "2.5.6.70006"),
    "Mists": ("wow_classic", "5.5.4.70579"),
}


def fetch(url, path):
    if not os.path.exists(path):
        # wago.tools refuses Python's default user agent.
        request = urllib.request.Request(url, headers={"User-Agent": "BetterBags tools/atlas_sizes"})
        with urllib.request.urlopen(request, timeout=120) as r, open(path, "wb") as f:
            f.write(r.read())
    return path


def table(cache, name, build):
    path = os.path.join(cache, f"{name}_{build}.csv")
    fetch(f"https://wago.tools/db2/{name}/csv?build={build}", path)
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def sizes(cache, build):
    elements = {r["ID"]: r["Name"] for r in table(cache, "UiTextureAtlasElement", build)}
    members = {}
    for r in table(cache, "UiTextureAtlasMember", build):
        members.setdefault(r["UiTextureAtlasElementID"], []).append(r)
    out = {}
    for eid, name in elements.items():
        rows = members.get(eid)
        if not rows:
            continue
        one = [r for r in rows if not r["CommittedName"].lower().endswith("-2x")]
        if one:
            r, scale = one[0], 1
        else:
            r, scale = rows[0], 0.5
        flags = int(r["CommittedFlags"] or 0)
        out[name.lower()] = (name, int(r["Width"]) * scale, int(r["Height"]) * scale, bool(flags & 4), bool(flags & 2))
    return out


# Names a theme builds in code rather than writes out: Plain's tab(state) ("Options_Tab_" .. state .. "Left") and
# thumb(suffix) ("minimal-scrollbar-small-thumb-top" .. suffix).
BUILT = [f"Options_Tab_{state}{piece}" for state in ("", "Active_") for piece in ("Left", "Middle", "Right")] + [
    f"minimal-scrollbar-small-thumb-{piece}{suffix}" for piece in ("top", "middle", "bottom") for suffix in ("", "-over", "-down")]


def wanted():
    names = set(BUILT)
    for path in glob.glob("sonata/themes/next/*.lua") + glob.glob("sonata/themes/*.lua"):
        names.update(re.findall(r'"([A-Za-z0-9_!\-]+)"', open(path).read()))
    names.update(re.findall(r'atlas\s*=\s*"([^"]+)"', open("spec/fixtures/nineslice_layouts.lua").read()))
    return {n.lower() for n in names}


def number(v):
    return str(int(v)) if float(v).is_integer() else str(v)


def main():
    cache = sys.argv[1]
    os.makedirs(cache, exist_ok=True)
    names = wanted()
    families = {}
    for family, (_, build) in BUILDS.items():
        all_sizes = sizes(cache, build)
        families[family] = {k: v for k, v in all_sizes.items() if k in names}
    lines = [
        "-- atlas_sizes.lua -- generated by tools/atlas_sizes/generate.py; do not edit. Each client's atlas sizes",
        "-- (C_Texture.GetAtlasInfo: width, height, tilesHorizontally, tilesVertically) for the atlases BetterBags' themes",
        "-- name, from the client's UiTextureAtlasElement and UiTextureAtlasMember tables (wago.tools), builds: "
        + ", ".join(f"{f} {b}" for f, (_, b) in BUILDS.items()) + ".",
        "return {",
    ]
    for family in BUILDS:
        lines.append(f"  {family} = {{")
        for key in sorted(families[family]):
            name, w, h, th, tv = families[family][key]
            lines.append(f'    ["{name}"] = {{ {number(w)}, {number(h)}, {str(th).lower()}, {str(tv).lower()} }},')
        lines.append("  },")
    lines.append("}")
    with open("spec/fixtures/atlas_sizes.lua", "w") as f:
        f.write("\n".join(lines) + "\n")
    for family in BUILDS:
        print(family, len(families[family]))


if __name__ == "__main__":
    main()
