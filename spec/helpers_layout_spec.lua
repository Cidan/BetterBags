-- helpers_layout_spec.lua -- The spec layout resolver and pixel check (spec/helpers/layout.lua,
-- docs/next-pixel-perfect.md): rects from anchors the way the client works them out, and every
-- shown region on whole screen pixels.
local layout = dofile("spec/helpers/layout.lua")

describe("the spec layout resolver", function()
  local restore

  before_each(function()
    -- 1536 x 768 pixels at a UI scale of 1: a unit is a pixel.
    restore = layout.UseScreen(1536, 768, 1)
  end)

  after_each(function()
    restore()
  end)

  local function rect(region)
    local r = layout.Rect(region)
    return r and { r.left, r.right, r.top, r.bottom }
  end

  it("places a frame by its point on its relative frame's point, offset in its own units", function()
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetSize(100, 40)
    f:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 10, -20)
    assert.are.same({ 10, 110, 748, 708 }, rect(f))
    f:ClearAllPoints()
    f:SetPoint("BOTTOMRIGHT", UIParent, "BOTTOMRIGHT", -6, 4)
    assert.are.same({ 1430, 1530, 44, 4 }, rect(f))
    f:ClearAllPoints()
    f:SetPoint("CENTER")
    assert.are.same({ 718, 818, 404, 364 }, rect(f), "its parent's middle, by default")
  end)

  it("takes its size on an axis from two anchors there, and its parent by default", function()
    local parent = CreateFrame("Frame", nil, UIParent)
    parent:SetSize(200, 100)
    parent:SetPoint("BOTTOMLEFT", UIParent, "BOTTOMLEFT", 0, 0)
    local child = parent:CreateTexture()
    child:SetPoint("TOPLEFT", 5, -5)
    child:SetPoint("BOTTOMRIGHT", -5, 5)
    assert.are.same({ 5, 195, 95, 5 }, rect(child))
    child:ClearAllPoints()
    child:SetAllPoints()
    assert.are.same({ 0, 200, 100, 0 }, rect(child))
  end)

  -- A scaled frame's offsets and size are in its own units (lift:Place divides by its scale).
  it("works in each region's own units, its parents' scales multiplied", function()
    local panel = CreateFrame("Frame", nil, UIParent)
    panel:SetScale(0.5)
    panel:SetSize(200, 100)
    panel:SetPoint("BOTTOMLEFT", UIParent, "BOTTOMLEFT", 100, 50)
    assert.are.same({ 50, 150, 75, 25 }, rect(panel))
    local inner = CreateFrame("Frame", nil, panel)
    inner:SetSize(20, 10)
    inner:SetPoint("TOPLEFT", panel, "TOPLEFT", 10, -10)
    assert.are.same({ 55, 65, 70, 65 }, rect(inner))
  end)

  it("sizes a font string by its text unless given a size", function()
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetSize(100, 100)
    f:SetPoint("BOTTOMLEFT")
    local text = f:CreateFontString()
    text:SetFontObject(GameFontNormal)
    text:SetText("abcd")
    text:SetPoint("TOPLEFT", f, "TOPLEFT", 0, 0)
    assert.are.same({ 0, 24, 100, 88 }, rect(text), "6 per character, 12 high")
    text:SetWidth(50)
    assert.are.same({ 0, 50, 100, 88 }, rect(text))
  end)

  it("places nothing it cannot: no anchor, or an anchor to a frame not placed", function()
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetSize(10, 10)
    assert.is_nil(layout.Rect(f))
    local g = CreateFrame("Frame", nil, UIParent)
    g:SetPoint("TOPLEFT", f, "TOPLEFT", 0, 0)
    assert.is_nil(layout.Rect(g))
  end)

  it("keeps a rect a spec gave a region", function()
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetScale(2)
    f:_SetRect(10, 20, 30, 40)
    assert.are.same({ 20, 80, 120, 40 }, rect(f))
  end)

  -- The client reports a region's resolved size, also when only its anchors size it
  -- (warcraft.wiki.gg Region:GetWidth); the plain mock reports the size set. While a screen is set up
  -- (UseScreen) a region with no size of its own on an axis reports the size its anchors give it.
  it("reports the size anchors give a region while a screen is set up, the size set otherwise", function()
    restore()
    local plain = _G.__mockWidgetMethods.GetWidth
    assert.are.equal(0, CreateFrame("Frame", nil, UIParent):GetWidth())
    local undo = layout.UseScreen(1920, 1080, 1)
    local parent = CreateFrame("Frame", nil, UIParent)
    parent:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 0, 0)
    parent:SetSize(300, 200)
    local child = CreateFrame("Frame", nil, parent)
    child:SetPoint("TOPLEFT", parent, "TOPLEFT", 10, -5)
    child:SetPoint("BOTTOMRIGHT", parent, "BOTTOMRIGHT", -20, 15)
    assert.are.same({ 270, 180 }, { child:GetSize() })
    local half = CreateFrame("Frame", nil, parent)
    half:SetScale(0.5)
    half:SetAllPoints(parent)
    assert.are.same({ 600, 400 }, { half:GetSize() }, "in its own units")
    local sized = CreateFrame("Frame", nil, parent)
    sized:SetPoint("TOPLEFT", parent, "TOPLEFT", 0, 0)
    sized:SetSize(40, 30)
    assert.are.same({ 40, 30 }, { sized:GetSize() }, "the size set")
    local loose = CreateFrame("Frame", nil, UIParent)
    assert.are.same({ 0, 0 }, { loose:GetSize() }, "nothing placing it")
    undo()
    assert.are.equal(plain, _G.__mockWidgetMethods.GetWidth, "the plain mock again")
    assert.are.same({ 0, 0 }, { child:GetSize() })
    restore = layout.UseScreen(1536, 768, 1)
  end)

  describe("the pixel check", function()
    it("passes regions on whole screen pixels and names the ones that are not", function()
      local undo = layout.UseScreen(3396, 1362, 0.65)
      local unit = (768 / 1362) / 0.65
      local window = CreateFrame("Frame", nil, UIParent)
      window:SetSize(100 * unit, 50 * unit)
      window:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 10 * unit, -20 * unit)
      window:SetClipsChildren(true)
      local good = window:CreateTexture()
      good:SetPoint("TOPLEFT", 2 * unit, -2 * unit)
      good:SetSize(4 * unit, unit)
      assert.are.same({}, layout.PixelCheck(window))
      local bad = window:CreateTexture()
      bad:SetPoint("TOPLEFT", 3, -2 * unit)
      bad:SetSize(4 * unit, 1)
      local problems = layout.PixelCheck(window, { owners = { window = { bad = bad } } })
      assert.are.equal(1, #problems)
      -- 3 units are 3.458 pixels at 65% on a screen 1362 pixels high; 1 unit tall, its bottom 1.153 down.
      assert.are.equal("window.bad: left 13.458, right 17.458, bottom 1338.847", problems[1])
      undo()
    end)

    it("skips what draws nothing at alpha 0, its own or a parent's, and judges a button's state art", function()
      local undo = layout.UseScreen(3396, 1362, 0.65)
      local unit = (768 / 1362) / 0.65
      local window = CreateFrame("Frame", nil, UIParent)
      window:SetSize(100 * unit, 50 * unit)
      window:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 0, 0)
      local glow = window:CreateTexture()
      glow:SetPoint("TOPLEFT", 0.3, 0)
      glow:SetSize(10, 10)
      glow:SetAlpha(0)
      assert.are.same({}, layout.PixelCheck(window))
      glow:SetAlpha(1)
      window:SetAlpha(0)
      assert.are.same({}, layout.PixelCheck(window))
      window:SetAlpha(1)
      assert.are.equal(1, #layout.PixelCheck(window))
      glow:Hide()
      local button = CreateFrame("Button", nil, window)
      button:SetPoint("TOPLEFT", 0.4, 0)
      button:SetSize(10 * unit, 10 * unit)
      button:SetNormalTexture("Interface\\Buttons\\WHITE8X8")
      local problems = layout.PixelCheck(window)
      assert.are.equal(1, #problems)
      assert.is_truthy(problems[1]:find("NormalTexture"), problems[1])
      undo()
    end)

    it("judges a frame only when it clips its children: its edges cut what is inside", function()
      local undo = layout.UseScreen(3396, 1362, 0.65)
      local window = CreateFrame("Frame", nil, UIParent)
      window:SetSize(100, 50)
      window:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 0.3, 0)
      assert.are.same({}, layout.PixelCheck(window), "draws nothing itself")
      window:SetClipsChildren(true)
      assert.are.equal(1, #layout.PixelCheck(window))
      undo()
    end)

    -- An edit box draws its text inside its insets (SimpleEditBoxAPIDocumentation, SetTextInsets): the text
    -- area's edges must be on whole pixels too.
    it("checks an edit box's text insets, in its own units, scaled", function()
      local undo = layout.UseScreen(3396, 1362, 0.65)
      local unit = (768 / 1362) / 0.65
      local window = CreateFrame("Frame", nil, UIParent)
      window:SetSize(100 * unit, 50 * unit)
      window:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 0, 0)
      local box = CreateFrame("EditBox", nil, window)
      box:SetPoint("TOPLEFT", window, "TOPLEFT", 0, 0)
      box:SetSize(40 * unit, 10 * unit)
      box:SetTextInsets(6 * unit, 2 * unit, 0, 0)
      assert.are.same({}, layout.PixelCheck(window))
      box:SetTextInsets(6, 2 * unit, 0, 0)
      local problems = layout.PixelCheck(window, { owners = { window = { box = box } } })
      -- 6 units are 6.916 pixels.
      assert.are.same({ "window.box: text inset left 6.916" }, problems)
      box:SetScale(2)
      box:SetSize(20 * unit, 5 * unit)
      box:SetTextInsets(3 * unit, unit, 0, 0)
      assert.are.same({}, layout.PixelCheck(window), "3 own units at a scale of 2 are 6 pixels")
      undo()
    end)

    it("checks a font string by its anchor points only, and skips what is hidden or skipped", function()
      local undo = layout.UseScreen(3396, 1362, 0.65)
      local unit = (768 / 1362) / 0.65
      local window = CreateFrame("Frame", nil, UIParent)
      window:SetSize(100 * unit, 50 * unit)
      window:SetPoint("TOPLEFT", UIParent, "TOPLEFT", 0, 0)
      local text = window:CreateFontString()
      text:SetFontObject(GameFontNormal)
      text:SetText("odd")
      text:SetPoint("TOPLEFT", 3 * unit, -3 * unit)
      assert.are.same({}, layout.PixelCheck(window), "its right edge is the text's")
      text:SetPoint("TOPLEFT", 3.5 * unit, -3 * unit)
      assert.are.equal(1, #layout.PixelCheck(window))
      text:Hide()
      assert.are.same({}, layout.PixelCheck(window))
      text:Show()
      assert.are.same({}, layout.PixelCheck(window, { skip = { [text] = true } }))
      window:Hide()
      assert.are.same({}, layout.PixelCheck(window))
      undo()
    end)
  end)
end)
