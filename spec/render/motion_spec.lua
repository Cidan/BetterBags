    it("forgets what showed when its root is forgotten", function()
      local a, b = button(), button()
      inPass({ { a, 0, "X" } })
      motion:Forget(key)
      released(a)
      assert.are.equal(0, inPass({ { b, 40, "X" } }))
      assert.are.equal(40, xOf(b))
    end)

    it("keeps each root's apart", function()
      local a, b = button(), button()
      inPass({ { a, 0, "X" } })
      released(a)
      motion:BeginPass({})
      motion:Place(b, parent, 40, 0, "X")
      assert.are.equal(0, motion:EndPass())
      assert.are.equal(40, xOf(b))
    end)

    it("puts at once outside a pass", function()
      local a = button()
      motion:Place(a, parent, 40, 0, "X")
      assert.are.equal(40, xOf(a))
      assert.is_nil(motion:GetMove(a))
    end)

    it("takes the place it showed when placed there last in a pass", function()
      local a = button()
      inPass({ { a, 0, "X" } })
      motion:BeginPass(key)
      motion:Place(a, parent, 40, 0, "X")
      motion:Place(a, parent, 0, 0, "X")
      assert.are.equal(0, motion:EndPass())
      assert.are.equal(0, xOf(a))
    end)

    it("moves from the place it showed when placed there first in a pass", function()
      local a = button()
      inPass({ { a, 0, "X" } })
      motion:BeginPass(key)
      motion:Place(a, parent, 0, 0, "X")
      motion:Place(a, parent, 80, 0, "X")
      motion:EndPass()
      assert.are.same({ 0, 0, 80, 0 }, { motion:GetMove(a) })
    end)

    it("takes the last place when a frame is placed twice in a pass", function()
      local a = button()
      inPass({ { a, 0, "X" } })
      motion:BeginPass(key)
      motion:Place(a, parent, 40, 0, "X")
      motion:Place(a, parent, 80, 0, "X")
      motion:EndPass()
      assert.are.same({ 0, 0, 80, 0 }, { motion:GetMove(a) })
    end)

    it("places what shows nothing in particular at once, before the pass ends, parents ahead of what is in them", function()
      local section = button()
      motion:BeginPass(key)
      motion:Place(section, parent, 40, 0)
      assert.are.equal(40, xOf(section))
      motion:EndPass()
    end)

    it("goes on moving a frame given no shows by where the frame was", function()
      local section = button()
      inPass({ { section, 0 } })
      assert.are.equal(1, inPass({ { section, 40 } }))
      assert.are.same({ 0, 0, 40, 0 }, { motion:GetMove(section) })
    end)

    describe("what an item button shows (ShownBy)", function()
      it("is its item's hash", function()
        local item = { GetItemData = function() return { itemHash = "h" } end }
        assert.are.equal("h", motion.ShownBy(item))
      end)

      it("is nothing for a free slot and an empty one", function()
        assert.are.equal(motion.NOTHING, motion.ShownBy({ isFreeSlot = true, GetItemData = function() return {} end }))
        assert.are.equal(motion.NOTHING, motion.ShownBy({ GetItemData = function() return { isItemEmpty = true } end }))
      end)

      it("says nothing about what is no item button, or holds no item", function()
        assert.is_nil(motion.ShownBy({}))
        assert.is_nil(motion.ShownBy({ GetItemData = function() return nil end }))
        assert.is_nil(motion.ShownBy({ GetItemData = function() return {} end }))
      end)
    end)
  end)
